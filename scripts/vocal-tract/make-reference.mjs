#!/usr/bin/env node
// Regenerates tests/platform/fixtures/vocaltract-reference.json by running the
// original VocalTract LaTeX package over its 26-entry demo codebook and
// recording every coordinate it computes. The port in
// src/lib/platform/vocal-tract/ is tested against this file.
//
// Needs a TeX distribution with the vocaltract, pstricks, pst-coil, arrayjob,
// fp, fltpoint, multido and animate packages (TeX Live full has them all).
// Set VOCALTRACT_STY to use a VocalTract.sty other than the installed one.
//
//   node scripts/vocal-tract/make-reference.mjs
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const out = join(root, "tests/platform/fixtures/vocaltract-reference.json");

const sty =
  process.env.VOCALTRACT_STY ?? execFileSync("kpsewhich", ["VocalTract.sty"], { encoding: "utf8" }).trim();
if (!sty) throw new Error("VocalTract.sty not found; install the vocaltract package or set VOCALTRACT_STY.");

// TeX macro names -> the port's point names.
const NAMES = {
  HyoidDown: "hyoidDown",
  HyoidUp: "hyoidUp",
  EpiglotisBase: "epiglottisBase",
  TongueBase: "tongueBase",
  TonguePharynx: "tonguePharynx",
  Epiglotis: "epiglottis",
  TongueUvular: "tongueUvular",
  TongueVelar: "tongueVelar",
  TonguePalatal: "tonguePalatal",
  TonguePostAlv: "tonguePostAlveolar",
  vtngX: "tongueBladeBack",
  vtngY: "tongueBladeFront",
  TongueAlveolar: "tongueAlveolar",
  ChordsJointFront: "chordsFront",
  ChordsJointBack: "chordsBack",
  LipUpOut: "lipUpOut",
  LipUpIn: "lipUpIn",
  LipDownOut: "lipDownOut",
  LipDownIn: "lipDownIn",
  ChinUp: "chinUp",
  ChinMiddle: "chinMiddle",
  ChinDown: "chinDown",
  LipDownBaseOut: "lipDownBaseOut",
  TeethDownBaseIn: "teethDownBaseIn",
  TeethDownEdge: "teethDownEdge",
  TeethDownBaseOut: "teethDownBaseOut",
  SubTongueSal: "subTongue",
  NasalCavMov: "velumBack",
};

const work = mkdtempSync(join(tmpdir(), "vocaltract-"));
try {
  copyFileSync(join(here, "reference.tex"), join(work, "reference.tex"));
  copyFileSync(sty, join(work, "VocalTract.sty"));
  execFileSync("latex", ["-interaction=nonstopmode", "-halt-on-error", "-no-shell-escape", "reference.tex"], {
    cwd: work,
    stdio: "ignore",
  });

  const frames = [];
  let frame = null;
  for (const line of readFileSync(join(work, "vocaltract-points.txt"), "utf8").split("\n")) {
    const [name, a, b] = line.trim().split(/\s+/);
    if (!name) continue;
    if (name === "FRAME") {
      frame = { index: Number(a), points: {}, glottis: null };
      frames.push(frame);
    } else if (name === "GLOTTIS") {
      frame.glottis = { aperture: Number(a), frequency: Number(b) };
    } else if (NAMES[name]) {
      frame.points[NAMES[name]] = [Number(a), Number(b)];
    } else {
      throw new Error(`Unexpected line from TeX: ${line}`);
    }
  }
  if (frames.length !== 26) throw new Error(`Expected 26 frames, got ${frames.length}.`);

  const styText = readFileSync(sty);
  const fixture = {
    about:
      "Coordinates computed by the original VocalTract LaTeX package (Ververidis, CTAN pkg/vocaltract) for its demo codebook. Generated by scripts/vocal-tract/make-reference.mjs; do not edit by hand.",
    source: {
      file: "VocalTract.sty",
      sha256: createHash("sha256").update(styText).digest("hex"),
      tex: execFileSync("latex", ["--version"], { encoding: "utf8" }).split("\n")[0],
    },
    frames,
  };
  const json = JSON.stringify(fixture, null, 1).replace(/\[\s+(-?[\d.]+),\s+(-?[\d.]+)\s+\]/g, "[$1, $2]");
  writeFileSync(out, `${json}\n`);
  console.log(`wrote ${out} (${frames.length} frames)`);
} finally {
  rmSync(work, { recursive: true, force: true });
}

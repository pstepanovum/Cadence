#!/usr/bin/env node
// Copies the illustrations the app draws (onboarding, the paywall, badges)
// from public/illustration into one generated module of SVG strings, so
// react-native-svg can recolour them for dark mode at render time.
//
//   node scripts/sync-illustrations.mjs           write src/data/illustrations.generated.ts
//   node scripts/sync-illustrations.mjs --check   fail if it is out of date

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const mobile = resolve(here, "..");
const source = resolve(mobile, "../public/illustration");
const target = join(mobile, "src/data/illustrations.generated.ts");

/** Name in the app, file in public/illustration. */
const PICK = {
  welcome: "following-your-dreams-1.svg",
  talk: "communication-1.svg",
  progress: "progress-1.svg",
  goal: "figuring-it-out-1.svg",
  level: "analysing-1.svg",
  daily: "daily-activity-1.svg",
  reminders: "always-in-hurry-1.svg",
  place: "navigating--1.svg",
  account: "getting-help-1.svg",
  success: "success-1.svg",
  badges: "overcome-problems-1.svg",
};

const entries = Object.entries(PICK).map(([name, file]) => {
  const svg = readFileSync(join(source, file), "utf8").replace(/\s+/g, " ").replace(/> </g, "><").trim();
  return `  ${name}: ${JSON.stringify(svg)},`;
});

const body = `// GENERATED by mobile/scripts/sync-illustrations.mjs from public/illustration. Do not edit.


export const ILLUSTRATIONS = {
${entries.join("\n")}
} as const;

export type IllustrationName = keyof typeof ILLUSTRATIONS;
`;

if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== body) {
    console.error("src/data/illustrations.generated.ts is out of date; run node scripts/sync-illustrations.mjs");
    process.exit(1);
  }
  console.log("Illustrations are current.");
} else {
  writeFileSync(target, body);
  console.log(`Wrote ${Object.keys(PICK).length} illustrations (${Math.round(body.length / 1024)} KB).`);
}
